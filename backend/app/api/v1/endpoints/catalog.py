from typing import Any

from fastapi import APIRouter, HTTPException

from app.schemas.catalog import RulesResponse
from app.schemas.submit import ErrorResponse
from app.services import benchmark, detector

router = APIRouter()


@router.get("/rules", response_model=RulesResponse, summary="The detection rule catalog")
def rules() -> dict:
    """List every detection rule with its category, weight and description, the score bands (safe to critical)
    and the score at which input is blocked. The last rule, `XSS099`, is derived: it is added when decoding
    changed the input, not matched by a pattern.
    """
    return detector.rules_catalog()


@router.get(
    "/benchmark",
    response_model=dict[str, Any],
    responses={
        404: {"model": ErrorResponse, "description": "The report has not been generated yet"},
        500: {"model": ErrorResponse, "description": "The report file is unreadable"},
    },
    summary="The latest detector benchmark",
)
def get_benchmark() -> dict:
    """Return `reports/benchmark.json` as generated by `python -m xss_detector evaluate`: the test-set sizes, the
    metrics of each detector (recall, precision, false-positive rate, confusion counts and example misses), the
    per-source "unseen list" results and the caveats. The JSON is passed through unchanged.
    """
    try:
        return benchmark.load_benchmark()
    except benchmark.BenchmarkMissing:
        raise HTTPException(404, "Benchmark not generated; run python -m xss_detector evaluate")
    except benchmark.BenchmarkUnreadable:
        raise HTTPException(500, "Benchmark file is unreadable")
